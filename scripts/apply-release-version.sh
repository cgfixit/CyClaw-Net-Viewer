#!/bin/bash
# Stamp VERSION and CFBundleVersion onto Cargo.toml, Cargo.lock, and Info.plist.
# The package version, the netboard lockfile entry, CFBundleShortVersionString,
# and CFBundleVersion are the only fields changed.
#
#   ./scripts/apply-release-version.sh 0.2.1 5
#   ./scripts/apply-release-version.sh --root DIR 0.2.1 5
#   ./scripts/apply-release-version.sh --self-test
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TREE="$ROOT"

usage() {
  echo "Usage: $0 [--root DIR] VERSION BUNDLE_VERSION | $0 --self-test" >&2
}

apply_version() {
  local version="$1" bundle="$2"
  if ! printf '%s' "$version" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$'; then
    echo "::error::version '${version}' must look like 0.2.1" >&2
    exit 1
  fi
  if ! printf '%s' "$bundle" | grep -Eq '^[1-9][0-9]*$'; then
    echo "::error::CFBundleVersion '${bundle}' must be a positive integer" >&2
    exit 1
  fi
  python3 - "$TREE" "$version" "$bundle" <<'PY'
import pathlib, re, sys
root = pathlib.Path(sys.argv[1])
version, bundle = sys.argv[2], sys.argv[3]

def read_text(path):
    with path.open("r", encoding="utf-8", newline="") as handle:
        return handle.read()

def write_text(path, text):
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(text)

def replace_package_version(text):
    match = re.search(r"(?ms)^\[package\]\n.*?(?=^\[|\Z)", text)
    if not match:
        raise SystemExit("Cargo.toml has no [package] table")
    body = match.group(0)
    new_body, count = re.subn(
        r'(?m)^version = "[^"]+"',
        f'version = "{version}"',
        body,
        count=1,
    )
    if count != 1:
        raise SystemExit(f"Cargo.toml [package] version matches: {count}")
    return text[:match.start()] + new_body + text[match.end():]

def replace_lock_version(text):
    pattern = r'(\[\[package\]\]\nname = "netboard"\nversion = ")[^"]+(")'
    new, count = re.subn(pattern, rf'\g<1>{version}\g<2>', text, count=1)
    if count != 1:
        raise SystemExit(f"Cargo.lock netboard version matches: {count}")
    return new

def replace_plist(text, key, value):
    pattern = rf'(<key>{re.escape(key)}</key>\s*<string>)[^<]*(</string>)'
    new, count = re.subn(pattern, rf'\g<1>{value}\g<2>', text, count=1)
    if count != 1:
        raise SystemExit(f"{key} matches: {count}")
    return new

cargo = root / "Cargo.toml"
lock = root / "Cargo.lock"
plist = root / "Info.plist"
write_text(cargo, replace_package_version(read_text(cargo)))
write_text(lock, replace_lock_version(read_text(lock)))
plist_text = replace_plist(read_text(plist), "CFBundleShortVersionString", version)
plist_text = replace_plist(plist_text, "CFBundleVersion", bundle)
write_text(plist, plist_text)
PY
}

self_test() {
  local fixture out version bundle
  fixture="$(mktemp -d)"
  cat > "${fixture}/Cargo.toml" <<'EOF'
[package]
name = "netboard"
version = "0.2.0"
edition = "2021"

[dependencies]
eframe = { version = "=0.31.1" }
other = { version = "0.2.0" }
EOF
  cat > "${fixture}/Cargo.lock" <<'EOF'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "eframe"
version = "0.31.1"

[[package]]
name = "netboard"
version = "0.2.0"
dependencies = [
 "eframe",
]

[[package]]
name = "other"
version = "0.2.0"
EOF
  cat > "${fixture}/Info.plist" <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0"><dict>
	<key>CFBundleShortVersionString</key>
	<string>0.2.0</string>
	<key>CFBundleVersion</key>
	<string>4</string>
	<key>NSHumanReadableCopyright</key>
	<string>MIT. Not affiliated with Microsoft or Sysinternals.</string>
</dict></plist>
EOF
  "$0" --root "$fixture" 0.2.1 5
  python3 - "$fixture" <<'PY'
import pathlib, sys
root = pathlib.Path(sys.argv[1])
cargo = (root / "Cargo.toml").read_text(encoding="utf-8")
lock = (root / "Cargo.lock").read_text(encoding="utf-8")
plist = (root / "Info.plist").read_text(encoding="utf-8")
checks = [
    ('package version', 'version = "0.2.1"' in cargo.split("[dependencies]", 1)[0]),
    ('dependency pin', 'version = "=0.31.1"' in cargo),
    ('dependency 0.2.0', 'version = "0.2.0"' in cargo),
    ('lock format', '\nversion = 4\n' in lock),
    ('lock netboard', 'name = "netboard"\nversion = "0.2.1"' in lock),
    ('lock other', 'name = "other"\nversion = "0.2.0"' in lock),
    ('lock eframe', 'name = "eframe"\nversion = "0.31.1"' in lock),
    ('short version', "<key>CFBundleShortVersionString</key>\n\t<string>0.2.1</string>" in plist),
    ('bundle version', "<key>CFBundleVersion</key>\n\t<string>5</string>" in plist),
    ('copyright', "Not affiliated with Microsoft or Sysinternals." in plist),
]
failed = [name for name, ok in checks if not ok]
if failed:
    raise SystemExit("fixture mismatch: " + ", ".join(failed))
PY

  local real before after
  real="$(mktemp -d)"
  cp "$ROOT/Cargo.toml" "$ROOT/Cargo.lock" "$ROOT/Info.plist" "$real/"
  before="$(cksum "$ROOT/Cargo.toml" "$ROOT/Cargo.lock" "$ROOT/Info.plist")"
  out="$("$ROOT/scripts/next-release-version.sh" --read-tree --root "$real")"
  version="$(printf '%s\n' "$out" | awk -F= '$1=="version"{print $2}')"
  bundle="$(printf '%s\n' "$out" | awk -F= '$1=="bundle_version"{print $2}')"
  "$0" --root "$real" "$version" "$bundle"
  out="$("$ROOT/scripts/next-release-version.sh" --read-tree --root "$real" --occupied "$version" --seen-bundle "$bundle")"
  local next_version next_bundle
  next_version="$(printf '%s\n' "$out" | awk -F= '$1=="version"{print $2}')"
  next_bundle="$(printf '%s\n' "$out" | awk -F= '$1=="bundle_version"{print $2}')"
  python3 - "$real" "$version" "$bundle" "$ROOT/Cargo.lock" <<'PY'
import pathlib, re, sys
root = pathlib.Path(sys.argv[1])
version, bundle = sys.argv[2], sys.argv[3]
original_lock = pathlib.Path(sys.argv[4]).read_text(encoding="utf-8")
cargo = (root / "Cargo.toml").read_text(encoding="utf-8")
lock = (root / "Cargo.lock").read_text(encoding="utf-8")
plist = (root / "Info.plist").read_text(encoding="utf-8")
package = re.search(r"(?ms)^\[package\]\n(.*?)(?=^\[|\Z)", cargo)
found = re.search(r'(?m)^version = "([^"]+)"', package.group(1)).group(1)
if found != version:
    raise SystemExit(f"Cargo.toml package version is {found}, expected {version}")
if f'name = "netboard"\nversion = "{version}"' not in lock:
    raise SystemExit("Cargo.lock netboard version was not updated")
if not re.search(rf"<key>CFBundleShortVersionString</key>\s*<string>{re.escape(version)}</string>", plist):
    raise SystemExit("CFBundleShortVersionString was not updated")
if not re.search(rf"<key>CFBundleVersion</key>\s*<string>{re.escape(bundle)}</string>", plist):
    raise SystemExit("CFBundleVersion was not updated")
if 'version = "0.2.32"' not in lock or 'name = "ab_glyph"' not in original_lock:
    if "ab_glyph" in original_lock and 'version = "0.2.32"' not in lock:
        raise SystemExit("ab_glyph version changed")
if "\nversion = 4\n" not in lock:
    raise SystemExit("Cargo.lock format version changed")
PY
  after="$(cksum "$ROOT/Cargo.toml" "$ROOT/Cargo.lock" "$ROOT/Info.plist")"
  rm -rf "$fixture" "$real"
  if [ "$before" != "$after" ]; then
    echo "FAIL self-test modified the repository" >&2
    exit 1
  fi
  if [ -z "$next_version" ] || [ -z "$next_bundle" ]; then
    echo "FAIL round-trip did not produce the following version" >&2
    exit 1
  fi
  echo "PASS apply fixture 0.2.1 CFBundleVersion 5"
  echo "PASS real tree round-trip to ${version} CFBundleVersion ${bundle} (next would be ${next_version} / ${next_bundle})"
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --root)
      TREE="$2"
      shift 2
      ;;
    --self-test)
      self_test
      exit 0
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    --)
      shift
      break
      ;;
    -*)
      echo "unknown option: $1" >&2
      usage
      exit 2
      ;;
    *)
      break
      ;;
  esac
done

if [ "$#" -ne 2 ]; then
  usage
  exit 2
fi

apply_version "$1" "$2"
